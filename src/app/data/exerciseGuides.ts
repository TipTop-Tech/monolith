export function getExerciseGuide(name?: string | null): ExerciseGuide | undefined {
  if (!name) return undefined;
  const guide = GUIDES[name.trim().toLowerCase()];
  if (!guide && import.meta.env.DEV) {
    console.warn(`No exercise guide found for "${name}"`);
  }
  return guide;
}
